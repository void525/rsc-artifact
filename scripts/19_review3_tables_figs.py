def main() -> int:
    args = base_parser("review round 3 tables and figures").parse_args()
    cfg = load_config(args)
    primary = cfg["protocol"].get("primary_regime", "finite")
    keys = [f"{t}/{d}" for t in teachers(cfg) for d in main_domains(cfg)]
    stats = {k: read_json(ROOT / cfg["paths"]["runs"] / "stats" / k.split("/")[0] / f"{k.split('/')[1]}.json") for k in keys}
    a8 = ROOT / "runs" / "a8_split"
    use_a8 = all((a8 / t / f"{d}.json").exists() for t in teachers(cfg) for d in main_domains(cfg))
    r3_root = a8 if use_a8 else (ROOT / cfg["paths"]["runs"] / "review3")
    r3 = {k: read_json(r3_root / k.split("/")[0] / f"{k.split('/')[1]}.json") for k in keys}
    tab_dir, fig_dir = ensure_dir(ROOT / "paper" / "tables"), ensure_dir(ROOT / "paper" / "figures")
    (tab_dir / "tab_main_v3.tex").write_text(main_table(keys, stats, r3, primary), encoding="utf-8")
    (tab_dir / "tab_anatomy_v3.tex").write_text(anatomy_table(keys, stats, r3), encoding="utf-8")
    (tab_dir / "tab_orders_v3.tex").write_text(orders_table(keys, r3), encoding="utf-8")
    passes: Dict[str, list] = {}
    rep_dirs = sorted((ROOT / cfg["paths"]["runs"] / "throughput_rep").glob("pass*"))
    for k in keys:
        t, d = k.split("/")
        P = [read_json(ROOT / cfg["paths"]["runs"] / "throughput" / t / f"{d}.json")]
        for rd in rep_dirs:
            p = rd / t / f"{d}.json"
            if p.exists():
                v = read_json(p)
                if all(m in v["methods"] and "32" in v["methods"][m] for m in ("full", "rsc", "rsc_blockers", "prefix_uniform", "prefix_adaptive")):
                    P.append(v)
        passes[k] = P
    txt, npass = throughput_table(keys, passes)
    (tab_dir / "tab_throughput_v3.tex").write_text(txt, encoding="utf-8")
    orders_figure(keys, r3, fig_dir / "fig_orders.pdf")
    ladder_figure(keys, stats, r3, fig_dir / "fig_ladder.pdf")
    log(f"review-3 tables -> {tab_dir} (throughput passes per cell: {npass}); figure -> {fig_dir / 'fig_orders.pdf'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
