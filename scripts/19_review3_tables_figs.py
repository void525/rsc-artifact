def throughput_table(keys, passes_by_key):
    methods = [("rsc", "16/8"), ("rsc_blockers", "blockers"), ("prefix_uniform", "unif."), ("prefix_adaptive", "adapt.")]
    npass = min(len(v) for v in passes_by_key.values())
    L = header(f"GPU-seconds per query at C = 32 relative to the full teacher, mean and half-range over {npass} timed passes")
    L += ["\\begin{tabular}{@{}lrrrrr@{}}", "\\toprule",
          " & full & \\multicolumn{2}{c}{\\method{}} & \\multicolumn{2}{c}{prefix at once} \\\\", "\\cmidrule(lr){3-4}\\cmidrule(lr){5-6}",
          "Configuration & q/s & " + " & ".join(lab for _, lab in methods) + " \\\\", "\\midrule"]
    for k in keys:
        P = passes_by_key[k]
        fq = np.mean([p["methods"]["full"]["32"]["throughput_qps"] for p in P])
        cells = []
        for m, _ in methods:
            r = [p["methods"][m]["32"]["gpu_s_per_query"] / p["methods"]["full"]["32"]["gpu_s_per_query"] for p in P]
            mean, half = float(np.mean(r)), (max(r) - min(r)) / 2
            txt = f"{mean:.2f}\\,$\\pm$\\,{half:.2f}"
            cells.append(f"\\textbf{{{txt}}}" if max(r) < 1 else txt)
        L.append(f"{TSHORT[k.split('/')[0]]}/{DSHORT[k.split('/')[1]]} & {fq:.2f} & " + " & ".join(cells) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(L) + "\n", npass


