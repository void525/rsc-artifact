def grids_table(cfg, stats):
    """k grid (E4), r frontier (E5), batch sizes (E3), N (E6): RSC risk and calls per configuration."""
    rows = []  # (group, label, method key)
    for k in cfg["protocol"]["k_grid"]:
        rows.append(("$k$", f"$k={k}$", "E4", f"rsc_k{k}", "risk"))
    for r in cfg["protocol"]["r_grid"]:
        rows.append(("$r$", f"$r={r}$ (risk $=\\ell_{r}$)", "E5", f"rsc_r{r}", "risk_ell_r"))
    for b in cfg["protocol"]["batch_grid"]:
        rows.append(("batch", f"$b={b}$", "E3", f"rsc_batch{b}", "risk"))
    for N in cfg["candidates"]["N_grid"]:
        rows.append(("$N$", f"$N={N}$", "E6", f"rsc_N{N}", "risk"))
    lines = header("grids") + ["\\begin{tabular}{@{}ll" + "rr" * len(stats) + "@{}}", "\\toprule",
                               "Grid & Setting & " + " & ".join(f"\\multicolumn{{2}}{{c}}{{{cfg_short(k)}}}" for k in stats) + " \\\\",
                               " & & " + " & ".join("risk & calls" for _ in stats) + " \\\\", "\\midrule"]
    last_group = None
    for group, label, exp, mkey, rk in rows:
        cells = []
        any_val = False
        for st in stats.values():
            v = st.get(exp, {}).get(mkey)
            if v and isinstance(v, dict):
                any_val = True
                cells.append(f"{fmt(v.get(rk, v.get('risk')), 4)} & {fmt(v['calls_mean'], 1)}")
            else:
                cells.append("-- & --")
        if not any_val:
            continue
        if last_group is not None and group != last_group:
            lines.append("\\midrule")
        lines.append((group if group != last_group else "") + f" & {label} & " + " & ".join(cells) + " \\\\")
        last_group = group
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def schedule_table(cfg, stats):
    """E3/E3b: fixed batch schedules vs blocker batches -- calls / rounds / risk per configuration (same lambda)."""
    order = []
    for st in stats.values():
        for m in st.get("E3", {}):
            if isinstance(st["E3"][m], dict) and "calls_mean" in st["E3"][m] and m.startswith("rsc_") and m not in order:
                order.append(m)
    order.sort(key=lambda m: (0, int(m.replace("rsc_batch", ""))) if m.startswith("rsc_batch") else (1, tuple(int(x) for x in m.replace("rsc_blockers", "").split("_"))))

    def label(m):
        if m.startswith("rsc_batch"):
            return f"fixed, batches of {m.split('batch')[1]}"
        if m.startswith("rsc_blockers"):
            a, b = m.replace("rsc_blockers", "").split("_")
            return f"blocker batches (first {a}, $\\ge${b})"
        return m

    def traj_cell(st, m):
        """risk of the fixed-trajectory threshold (calibrated on the main schedule) transferred to schedule m"""
        v = st.get("E3", {}).get(m.replace("rsc_", "traj_"))
        return fmt(v["risk"], 3) if v else "--"

    lines = header("batch schedules (E3, E3b)") + ["\\begin{tabular}{@{}l" + "r" * len(stats) + "@{}}", "\\toprule",
                                                     "Schedule (calls / rounds / risk [risk of the transferred fixed-trajectory threshold]) & " + " & ".join(cfg_short(k) for k in stats) + " \\\\", "\\midrule"]
    bf, br = cfg["protocol"]["batch_first"], cfg["protocol"]["batch_rest"]
    cells = []
    for st in stats.values():
        cells.append(f"{fmt(st['calls']['rsc_mean'], 1)} / {fmt(st['E1_rounds_mean'], 1) if 'E1_rounds_mean' in st else '--'} / {fmt(st['risk'][cfg['protocol'].get('primary_regime', 'finite')]['rate'], 3)}")
    lines.append(f"main: first {bf}, then {br} & " + " & ".join(cells) + " \\\\")
    for m in order:
        cells = []
        for st in stats.values():
            v = st.get("E3", {}).get(m)
            cells.append(f"{fmt(v['calls_mean'], 1)} / {fmt(v['rounds_mean'], 1)} / {fmt(v['risk'], 3)} [{traj_cell(st, m)}]" if v else "--")
        lines.append(f"{label(m)} & " + " & ".join(cells) + " \\\\")
    if all("union_over_schedules" in st.get("E3", {}) for st in stats.values()):
        lines.append("\\midrule")
        lines.append("union over schedules: RSC [traj.] & " + " & ".join(f"{fmt(st['E3']['union_over_schedules']['rsc']['union_risk'], 3)} [{fmt(st['E3']['union_over_schedules']['traj']['union_risk'], 3)}]" for st in stats.values()) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def cross_table(cfg, stats):
    """E7: source-domain thresholds applied to the cross domains (stress test)."""
    entries = []
    for key, st in stats.items():
        e7 = st.get("E7", {})
        for m, v in e7.items():
            if isinstance(v, dict) and "risk" in v:
                entries.append((key, m, v))
    if not entries:
        return "\n".join(header("cross-domain") + ["% (no cross-domain records)"]) + "\n"
    lines = header("cross-domain stress test") + ["\\begin{tabular}{@{}llrrrr@{}}", "\\toprule",
                                                  "Source config & Target / method & Risk & Calls & Early & nDCG@10 \\\\", "\\midrule"]
    last = None
    for key, m, v in entries:
        lines.append((cfg_short(key) if key != last else "") + f" & {m.replace('_', ' ')} & {fmt(v['risk'], 4)} & {fmt(v['calls_mean'], 1)} & {fmt(v.get('early_fraction'), 2)} & {fmt(v.get('ndcg@k'), 4)} \\\\")
        last = key
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


