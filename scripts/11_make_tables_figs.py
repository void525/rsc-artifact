def fmt(x, d=3):
    if x is None or (isinstance(x, float) and x != x):
        return "--"
    if isinstance(x, (int, np.integer)):
        return str(int(x))
    return f"{x:.{d}f}"


def pct(x, d=1):
    return "--" if x is None else f"{100 * x:.{d}f}"


def cfg_label(key: str) -> str:
    t, d = key.split("/")
    return f"{TEACHER_LABELS.get(t, t)} / {DOMAIN_LABELS.get(d, d)}"


def cfg_short(key: str) -> str:
    t, d = key.split("/")
    return f"{TEACHER_SHORT.get(t, t)}/{DOMAIN_LABELS.get(d, d)}"


def header(comment: str) -> List[str]:
    return [f"% AUTO-GENERATED by scripts/11_make_tables_figs.py -- {comment}. Do not edit by hand."]


