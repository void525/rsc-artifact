def latency_table(cfg, lat: Dict[str, dict]):
    """Compact main-text latency table: per configuration the full teacher's mean latency (ms) and every other method's
    mean latency as a ratio to it, in the controlled regime (cached teacher's micro-batch) and the tuned regime
    (per-method best micro-batch); last column: fraction of tuned-regime full-teacher queries whose top-k equals the cached top-k."""
    if not lat:
        return "\n".join(header("latency") + ["% (no latency measurements yet)"]) + "\n"
    methods = [("rsc", "RSC 16/8"), ("rsc_blockers", "RSC blockers"), ("prefix_uniform", "Unif.\\ prefix"), ("prefix_adaptive", "Ad.\\ prefix")]
    methods_t = [m for m in methods if m[0] != "rsc_blockers"]  # the blocker schedule was measured in the controlled regime only (A2)
    lines = header("real end-to-end latency, compact (ratios to the full teacher)") + ["\\begin{tabular}{@{}lr" + "r" * len(methods) + "r" + "r" * len(methods_t) + "r@{}}", "\\toprule",
             "Configuration & \\multicolumn{" + str(1 + len(methods)) + "}{c}{Controlled} & \\multicolumn{" + str(1 + len(methods_t)) + "}{c}{Tuned} & Top-$k$ \\\\",
             " & full (ms) & " + " & ".join(l for _, l in methods) + " & full (ms) & " + " & ".join(l for _, l in methods_t) + " & agree \\\\", "\\midrule"]

    def ratio(R, m):
        c = R.get(m)
        f = R.get("full")
        if not c or not f:
            return "--"
        x = c["latency_mean_s"] / f["latency_mean_s"]
        return (f"\\textbf{{{x:.2f}}}" if x < 1 else f"{x:.2f}") + "$\\times$"

    for key, d in lat.items():
        R = d["regimes"]
        C, T = R.get("controlled", {}), R.get("tuned", {})
        agree = T.get("full", {}).get("agree_with_cache")
        lines.append(f"{cfg_short(key)} & {1000 * C['full']['latency_mean_s']:.0f} & " + " & ".join(ratio(C, m) for m, _ in methods)
                     + f" & {1000 * T['full']['latency_mean_s']:.0f} & " + " & ".join(ratio(T, m) for m, _ in methods_t) + f" & {fmt(agree, 2)} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def latency_full_table(cfg, lat: Dict[str, dict]):
    """Appendix/artifact version with mean and p95 in ms, calls and top-k agreement for every method and regime."""
    if not lat:
        return "\n".join(header("latency, full") + ["% (no latency measurements yet)"]) + "\n"
    methods = [("full", "Full teacher"), ("rsc", "RSC-Rank (16 then 8)"), ("rsc_blockers", "RSC-Rank (blocker batches)"), ("prefix_uniform", "Uniform prefix"), ("prefix_adaptive", "Adaptive prefix")]
    lines = header("real end-to-end latency, full") + ["\\begin{tabular}{@{}llrrrrrrr@{}}", "\\toprule",
                                                       "Configuration & Method & Calls & \\multicolumn{3}{c}{Controlled} & \\multicolumn{3}{c}{Tuned} \\\\",
                                                       " & & & mean (ms) & p95 (ms) & agree & mean (ms) & p95 (ms) & agree \\\\", "\\midrule"]
    for key, d in lat.items():
        R = d["regimes"]
        first = True
        for m, label in methods:
            c, t = R.get("controlled", {}).get(m), R.get("tuned", {}).get(m)
            if not c and not t:
                continue
            calls = (c or t).get("calls_mean")

            def cell(x):
                return f"{1000 * x['latency_mean_s']:.0f} & {1000 * x['latency_p95_s']:.0f} & {fmt(x.get('agree_with_cache'), 2)}" if x else "-- & -- & --"

            lines.append((f"\\multirow{{{len(methods)}}}{{*}}{{{cfg_short(key)}}}" if first else "") + f" & {label} & {fmt(calls, 1)} & {cell(c)} & {cell(t)} \\\\")
            first = False
        lines.append("\\midrule")
    lines[-1] = "\\bottomrule"
    lines.append("\\end{tabular}")
    return "\n".join(lines) + "\n"


def throughput_table(cfg, thr: Dict[str, dict]):
    """Compact throughput table (A4): per configuration the full teacher's throughput at each concurrency and every
    other method's GPU-seconds per query as a ratio to the full teacher's (ratio < 1 = cheaper); bold = below 1."""
    if not thr:
        return "\n".join(header("throughput") + ["% (no throughput measurements yet)"]) + "\n"
    methods = [("rsc", "RSC 16/8"), ("rsc_blockers", "RSC blockers"), ("prefix_uniform", "Unif.\\ prefix"), ("prefix_adaptive", "Ad.\\ prefix")]
    Cs = sorted({int(c) for d in thr.values() for m in d["methods"].values() for c in m}, key=int)
    lines = header("throughput under concurrency (GPU-seconds per query, ratio to full)") + ["\\begin{tabular}{@{}l" + "".join("r" + "r" * len(methods) for _ in Cs) + "@{}}", "\\toprule",
             "Configuration & " + " & ".join(f"\\multicolumn{{{1 + len(methods)}}}{{c}}{{$C={c}$}}" for c in Cs) + " \\\\",
             " & " + " & ".join("full (q/s) & " + " & ".join(l for _, l in methods) for _ in Cs) + " \\\\", "\\midrule"]

    def ratio(d, m, c):
        r = d["methods"].get(m, {}).get(str(c))
        f = d["methods"].get("full", {}).get(str(c))
        if not r or not f:
            return "--"
        x = r["gpu_s_per_query"] / f["gpu_s_per_query"]
        return (f"\\textbf{{{x:.2f}}}" if x < 1 else f"{x:.2f}")

    for key, d in thr.items():
        cells = []
        for c in Cs:
            f = d["methods"].get("full", {}).get(str(c))
            cells.append((f"{f['throughput_qps']:.2f}" if f else "--") + " & " + " & ".join(ratio(d, m, c) for m, _ in methods))
        lines.append(f"{cfg_short(key)} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def envelope_table(cfg, env: Dict[str, dict]):
    """Policy-envelope table: thresholds and mu-order calls at the mu-trajectory, envelope and rank-sufficient thresholds;
    share of the premium needed for the tested orders; union failure of the transferred trajectory threshold."""
    if not env:
        return "\n".join(header("policy envelope") + ["% (no envelope analysis yet)"]) + "\n"
    lines = header("policy envelope (trajectory statistics per order vs the rank-sufficient statistic)") + ["\\begin{tabular}{@{}lrrrrrrrrrr@{}}", "\\toprule",
             "Configuration & $\\lambda^{\\mu}$ & $\\lambda^{\\mathrm{env}}$ & $\\lambda$ & calls @$\\lambda^{\\mu}$ & @$\\lambda^{\\mathrm{env}}_{\\mathrm{real}}$ & @$\\lambda^{\\mathrm{env}}$ & @$\\lambda$ & @$\\lambda^{\\mu}_{\\alpha/K}$ & env $>\\lambda^{\\mu}$ & real.\\ env $>\\lambda^{\\mu}$ \\\\", "\\midrule"]
    for key, v in env.items():
        th, cl, ps = v["thresholds"], v["calls_under_mu_order"], v["premium_split"]
        bonf = cl.get("mu_bonf", {}).get("calls_mean")
        real = cl.get("env_realistic", {}).get("calls_mean")
        re_ = v.get("realistic_envelope", {})
        lines.append(f"{cfg_short(key)} & {th['lambda_mu']:.3f} & {th['lambda_env']:.3f} & {th['lambda_rsc']:.3f} & {cl['mu']['calls_mean']:.1f} & {fmt(real, 1)} & {cl['env']['calls_mean']:.1f} & {cl['rsc']['calls_mean']:.1f} & {fmt(bonf, 1)} & {th['env_test_frac_above_lambda_mu']:.3f} & {fmt(re_.get('env_test_frac_above_lambda_mu'), 3)} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


