"""Register the matched-serving summary ranges from runs/matched_service/aggregate.json.

The run is post-hoc. It does not refit thresholds. Ranges are the min and max,
over the six teacher--domain configurations, of the three-pass means.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _common import ROOT, base_parser, load_config  # noqa: E402

from rscrank.io import read_json  # noqa: E402
from rscrank.provenance import register, render_numbers_tex  # noqa: E402


def _span(rows, name):
    xs = [r[name] for r in rows]
    return min(xs), max(xs)


def _write_matched_table(summary, path: Path) -> None:
    """One-column matched-server table: ratios, plus the largest p95 half-range on each order."""
    order = [("qwen3-4b", "nq"), ("qwen3-4b", "hotpotqa"), ("qwen3-4b", "msmarco"),
             ("bge-m3", "nq"), ("bge-m3", "hotpotqa"), ("bge-m3", "msmarco")]
    by = {(c["teacher"], c["domain"]): c for c in summary["configs"]}
    short = {("qwen3-4b", "nq"): "Qwen/NQ", ("qwen3-4b", "hotpotqa"): "Qwen/Hotpot",
             ("qwen3-4b", "msmarco"): "Qwen/MS", ("bge-m3", "nq"): "bge/NQ",
             ("bge-m3", "hotpotqa"): "bge/Hotpot", ("bge-m3", "msmarco"): "bge/MS"}
    halves = {"bm25": [], "alt": []}

    def pair(rsc, sett, highlight: bool):
        gpu = f"{rsc['gpu_s_per_query'] / sett['gpu_s_per_query']:.3f}"
        ratio = rsc["latency_p95_s"] / sett["latency_p95_s"]
        p95 = f"{ratio:.3f}"
        if highlight:
            p95 = r"\textbf{" + p95 + "}"
        return gpu, p95

    lines = [
        "% AUTO-GENERATED by scripts/21_matched_numbers.py. Do not edit by hand.",
        r"\begin{tabular}{@{}l rr rr@{}}",
        r"\toprule",
        r" & \multicolumn{2}{c}{BM25} & \multicolumn{2}{c}{other model} \\",
        r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}",
        r" & GPU & p95 & GPU & p95 \\",
        r"\midrule",
    ]
    for key in order:
        m = by[key]["methods"]
        mark = key == ("bge-m3", "msmarco")
        for tag, rk, sk in (("bm25", "rsc_bm25", "set_bm25"), ("alt", "rsc_mu_alt", "set_mu_alt")):
            halves[tag].append(m[rk]["latency_p95_half_range"])
            halves[tag].append(m[sk]["latency_p95_half_range"])
        cells = pair(m["rsc_bm25"], m["set_bm25"], False) + pair(m["rsc_mu_alt"], m["set_mu_alt"], mark)
        lines.append(short[key] + " & " + " & ".join(cells) + r" \\")
    lines.append(
        r"\midrule" + "\n"
        + r"max p95 half-range (s) & \multicolumn{2}{c}{"
        + f"{max(halves['bm25']):.3f}"
        + r"} & \multicolumn{2}{c}{"
        + f"{max(halves['alt']):.3f}"
        + r"} \\"
    )
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    args = base_parser("matched serving numbers").parse_args()
    cfg = load_config(args)
    src = ROOT / "runs" / "matched_service" / "aggregate.json"
    summary = read_json(src)
    if summary["passes"] != 3 or len(summary["configs"]) != 6:
        raise SystemExit(f"expected 3 passes and 6 configs, got {summary['passes']} passes and {len(summary['configs'])} configs")
    reg = ROOT / cfg["paths"]["runs"] / "provenance" / "registry.json"
    rows = []
    for cfg_row in summary["configs"]:
        m = cfg_row["methods"]
        sub, sb, rb, eb = m["submit_s"], m["set_bm25"], m["rsc_bm25"], m["env_bm25"]
        sa, ra, ea = m["set_mu_alt"], m["rsc_mu_alt"], m["env_mu_alt"]
        rows.append({
            "submit_gpu": sub["gpu_s_per_query"],
            "set_bm25_gpu": sb["gpu_s_per_query"],
            "rsc_bm25_gpu": rb["gpu_s_per_query"],
            "env_bm25_gpu": eb["gpu_s_per_query"],
            "set_alt_gpu": sa["gpu_s_per_query"],
            "rsc_alt_gpu": ra["gpu_s_per_query"],
            "env_alt_gpu": ea["gpu_s_per_query"],
            "rsc_over_set_bm25": rb["gpu_s_per_query"] / sb["gpu_s_per_query"],
            "rsc_over_set_alt": ra["gpu_s_per_query"] / sa["gpu_s_per_query"],
            "env_over_rsc_bm25": eb["gpu_s_per_query"] / rb["gpu_s_per_query"],
            "env_over_rsc_alt": ea["gpu_s_per_query"] / ra["gpu_s_per_query"],
            "submit_over_set_bm25": sub["gpu_s_per_query"] / sb["gpu_s_per_query"],
            "p95_rsc_over_set_bm25": rb["latency_p95_s"] / sb["latency_p95_s"],
            "p95_rsc_over_set_alt": ra["latency_p95_s"] / sa["latency_p95_s"],
            "p95_submit_over_set_bm25": sub["latency_p95_s"] / sb["latency_p95_s"],
            "inflight_rsc_bm25": rb["inflight_mean"],
            "inflight_rsc_alt": ra["inflight_mean"],
            "inflight_set_bm25": sb["inflight_mean"],
            "inflight_set_alt": sa["inflight_mean"],
            "calls_rsc_bm25": rb["calls_mean"],
            "calls_set_bm25": sb["calls_mean"],
            "calls_rsc_alt": ra["calls_mean"],
            "calls_set_alt": sa["calls_mean"],
            "calls_submit": sub["calls_mean"],
            "risk_rsc_bm25": rb["risk"],
            "risk_rsc_alt": ra["risk"],
            "risk_set_bm25": sb["risk"],
            "risk_set_alt": sa["risk"],
            "risk_submit": sub["risk"],
            "risk_env_bm25": eb["risk"],
            "risk_env_alt": ea["risk"],
            "spread_gpu": max(r["gpu_s_half_range"] / r["gpu_s_per_query"] for r in (sub, sb, rb, eb, sa, ra, ea)),
        })
    specs = {
        "MatchedRscOverSetBmTwoFiveGpuMin": (_span(rows, "rsc_over_set_bm25")[0], "smallest RSC/set-completion GPU-seconds ratio on the BM25 order"),
        "MatchedRscOverSetBmTwoFiveGpuMax": (_span(rows, "rsc_over_set_bm25")[1], "largest RSC/set-completion GPU-seconds ratio on the BM25 order"),
        "MatchedRscOverSetMuAltGpuMin": (_span(rows, "rsc_over_set_alt")[0], "smallest RSC/set-completion GPU-seconds ratio on the other cheap model order"),
        "MatchedRscOverSetMuAltGpuMax": (_span(rows, "rsc_over_set_alt")[1], "largest RSC/set-completion GPU-seconds ratio on the other cheap model order"),
        "MatchedSubmitOverSetBmTwoFiveGpuMin": (_span(rows, "submit_over_set_bm25")[0], "smallest submit-only-S / BM25-set-completion GPU-seconds ratio"),
        "MatchedSubmitOverSetBmTwoFiveGpuMax": (_span(rows, "submit_over_set_bm25")[1], "largest submit-only-S / BM25-set-completion GPU-seconds ratio"),
        "MatchedPNineFiveRscOverSetBmTwoFiveMin": (_span(rows, "p95_rsc_over_set_bm25")[0], "smallest RSC/set-completion p95 latency ratio on BM25"),
        "MatchedPNineFiveRscOverSetBmTwoFiveMax": (_span(rows, "p95_rsc_over_set_bm25")[1], "largest RSC/set-completion p95 latency ratio on BM25"),
        "MatchedPNineFiveRscOverSetMuAltMin": (_span(rows, "p95_rsc_over_set_alt")[0], "smallest RSC/set-completion p95 latency ratio on the other cheap model"),
        "MatchedPNineFiveRscOverSetMuAltMax": (_span(rows, "p95_rsc_over_set_alt")[1], "largest RSC/set-completion p95 latency ratio on the other cheap model"),
        "MatchedPNineFiveSubmitOverSetBmTwoFiveMin": (_span(rows, "p95_submit_over_set_bm25")[0], "smallest submit-only-S / BM25-set-completion p95 latency ratio"),
        "MatchedPNineFiveSubmitOverSetBmTwoFiveMax": (_span(rows, "p95_submit_over_set_bm25")[1], "largest submit-only-S / BM25-set-completion p95 latency ratio"),
        "MatchedInflightRscMin": (min(_span(rows, "inflight_rsc_bm25")[0], _span(rows, "inflight_rsc_alt")[0]), "smallest mean in-flight tail of RSC, either external order"),
        "MatchedInflightRscMax": (max(_span(rows, "inflight_rsc_bm25")[1], _span(rows, "inflight_rsc_alt")[1]), "largest mean in-flight tail of RSC, either external order"),
        "MatchedInflightSetMin": (min(_span(rows, "inflight_set_bm25")[0], _span(rows, "inflight_set_alt")[0]), "smallest mean in-flight tail of set completion, either external order"),
        "MatchedInflightSetMax": (max(_span(rows, "inflight_set_bm25")[1], _span(rows, "inflight_set_alt")[1]), "largest mean in-flight tail of set completion, either external order"),
        "MatchedRiskRscMax": (max(_span(rows, "risk_rsc_bm25")[1], _span(rows, "risk_rsc_alt")[1], _span(rows, "risk_env_bm25")[1], _span(rows, "risk_env_alt")[1]), "largest exact top-k mismatch of RSC or the envelope under either external order"),
        "MatchedRiskSubmitMax": (_span(rows, "risk_submit")[1], "largest exact top-k mismatch of submit-only-S"),
        "MatchedRiskSetMax": (max(_span(rows, "risk_set_bm25")[1], _span(rows, "risk_set_alt")[1]), "largest exact top-k mismatch of set completion under either external order"),
        "MatchedGpuHalfRangeFracMax": (_span(rows, "spread_gpu")[1], "largest half-range of GPU-seconds as a fraction of the three-pass mean"),
        "MatchedCallsRscMinusSetBmTwoFiveMin": (_span(rows, "calls_rsc_bm25")[0] - _span(rows, "calls_set_bm25")[1], "not used"),
    }
    # Call gaps are per configuration, so the span of (rsc - set) must be computed per row, not as min(rsc)-max(set).
    call_bm = [r["calls_rsc_bm25"] - r["calls_set_bm25"] for r in rows]
    call_alt = [r["calls_rsc_alt"] - r["calls_set_alt"] for r in rows]
    specs["MatchedCallGapBmTwoFiveMin"] = (min(call_bm), "smallest RSC minus set-completion calls on BM25 (negative means RSC uses fewer)")
    specs["MatchedCallGapBmTwoFiveMax"] = (max(call_bm), "largest RSC minus set-completion calls on BM25")
    specs["MatchedCallGapMuAltMin"] = (min(call_alt), "smallest RSC minus set-completion calls on the other cheap model")
    specs["MatchedCallGapMuAltMax"] = (max(call_alt), "largest RSC minus set-completion calls on the other cheap model")
    del specs["MatchedCallsRscMinusSetBmTwoFiveMin"]
    # The p95 ratio 1.146 is bge-m3 / MS MARCO / the other cheap model.
    worst = next(c for c in summary["configs"] if c["teacher"] == "bge-m3" and c["domain"] == "msmarco")
    specs["MatchedWorstPNinetyFiveRscHalf"] = (
        worst["methods"]["rsc_mu_alt"]["latency_p95_half_range"],
        "three-pass half-range, in seconds, of RSC p95 latency on the cell with the largest RSC/set p95 ratio",
    )
    specs["MatchedWorstPNinetyFiveSetHalf"] = (
        worst["methods"]["set_mu_alt"]["latency_p95_half_range"],
        "three-pass half-range, in seconds, of set-completion p95 latency on that same cell",
    )
    _write_matched_table(summary, ROOT / "paper" / "tables" / "tab_matched.tex")
    for key, (value, desc) in specs.items():
        digits = 3 if abs(value) < 10 else 1
        if "Risk" in key or "Frac" in key or "Over" in key or "Gap" in key or "Inflight" in key:
            digits = 3 if "Risk" in key or "Frac" in key or "Over" in key else 2
        register(key, float(value), str(src), desc, digits, reg)
    render_numbers_tex(ROOT / "paper" / "numbers.tex", reg, ROOT / "paper" / "numbers.json")
    for key in sorted(specs):
        print(f"{key}: {specs[key][0]:.4f}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
