"""Macros and the witness table for the analyses added after the post-freeze split -> paper/numbers_extra.tex,
paper/tables/tab_witness.tex

Sources (all computed from frozen scores, thresholds and the canonical cache; nothing here selects a threshold):
  runs/a8_split/grid_frontier.json          all-subset witness risk at the three guardrail thresholds and the
                                            checkpoint-grid critical value (scripts/22_grid_frontier.py)
  runs/a8_split/<teacher>/<domain>.json     deployed-order calls at those thresholds (calls_under_mu)
  runs/latency_tuned_diff/<t>/<d>.json      tuned micro-batch versus canonical cache (scripts/23_tuned_disagreement.py)
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _common import ROOT, base_parser, load_config, main_domains, teachers  # noqa: E402

from rscrank.io import read_json  # noqa: E402

TSHORT = {"qwen3-4b": "Qwen3-4B", "bge-m3": "bge-m3"}
DSHORT = {"nq": "NQ", "hotpotqa": "HotpotQA", "msmarco": "MS MARCO"}
TINY = {"qwen3-4b": "Qwen", "bge-m3": "bge"}
DTINY = {"nq": "NQ", "hotpotqa": "Hotpot", "msmarco": "MS"}


def main() -> int:
    cfg = load_config(base_parser("extra paper numbers").parse_args())
    alpha = float(cfg["protocol"]["alpha_main"])
    keys = [(t, d) for t in teachers(cfg) for d in main_domains(cfg)]
    a8 = ROOT / cfg["paths"]["runs"] / "a8_split"
    lines = ["% AUTO-GENERATED by scripts/24_extra_numbers.py -- DO NOT EDIT BY HAND", ""]

    def put(name, value, desc, src):
        lines.append(f"\\newcommand{{\\num{name}}}{{{value}}} % {desc} <- {src}")

    # ---- witness risk -------------------------------------------------------------------------------------------
    wp = a8 / "grid_frontier.json"
    witness = {k: read_json(wp)[f"{k[0]}/{k[1]}"]["all_subset_witness_risk"] for k in keys}
    worst = {k: {"R_traj": v["traj_mu"], "R_env": v["env13"], "R_rsc": v["rsc"]} for k, v in witness.items()}
    for tag, field in (("Traj", "R_traj"), ("Env", "R_env"), ("Rsc", "R_rsc")):
        vals = [worst[k][field] for k in keys]
        put(f"AggWorst{tag}Min", f"{min(vals):.4f}", f"smallest all-state witness risk, {tag} threshold", wp)
        put(f"AggWorst{tag}Max", f"{max(vals):.4f}", f"largest all-state witness risk, {tag} threshold", wp)
    put("AggWorstTrajAboveAlphaCount", sum(worst[k]["R_traj"] > alpha for k in keys), "configurations whose trajectory threshold has witness risk above alpha", wp)
    put("AggWorstEnvAboveAlphaCount", sum(worst[k]["R_env"] > alpha for k in keys), "configurations whose envelope threshold has witness risk above alpha", wp)

    # compact witness table: risk and deployed-order calls at the three thresholds
    rows = []
    for t, d in keys:
        calls = read_json(a8 / t / f"{d}.json")["calls_under_mu"]
        w = worst[(t, d)]
        cells = []
        for field, ckey in (("R_traj", "traj_mu"), ("R_env", "env_all13"), ("R_rsc", "rsc")):
            r = w[field]
            rs = f"{r:.3f}"
            rs = f"\\textcolor{{figred}}{{\\textbf{{{rs}}}}}" if r > alpha else rs
            cells += [rs, f"{calls[ckey]:.1f}"]
        rows.append(f"{TSHORT[t]}/{DSHORT[d]} & " + " & ".join(cells) + " \\\\")
    tab = ["% AUTO-GENERATED by scripts/24_extra_numbers.py from runs/a8_split/grid_frontier.json and calls_under_mu.",
           "\\begin{tabular}{@{}l@{\\hspace{5pt}}rr@{\\hspace{7pt}}rr@{\\hspace{7pt}}rr@{}}", "\\toprule",
           " & \\multicolumn{2}{c}{one trajectory} & \\multicolumn{2}{c}{13 named policies} & \\multicolumn{2}{c}{all subsets} \\\\",
           "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(l){6-7}",
           "Configuration & witness & calls & witness & calls & witness & calls \\\\", "\\midrule", *rows, "\\bottomrule", "\\end{tabular}"]
    (ROOT / "paper" / "tables" / "tab_witness.tex").write_text("\n".join(tab) + "\n", encoding="utf-8")

    # ---- checkpoint grid ----------------------------------------------------------------------------------------
    gp = a8 / "grid_frontier.json"
    g = read_json(gp)
    G = [g[f"{t}/{d}"] for t, d in keys]
    put("GridLastCheckpoint", G[0]["last_checkpoint_below_N"], "last checkpoint below N of the deployed 16/8 grid", gp)
    put("AggGridIdentityMaxDiff", f"{max(x['identity_max_abs_diff'] for x in G):.0f}", "largest |A_k1 - (s_(k+1) - mu_[H_k])/sigma| over all queries", gp)
    put("AggGridBelowAPctMax", f"{100 * max(max(x['cal_frac_grid_below_A'], x['test_frac_grid_below_A']) for x in G):.1f}", "largest share of calibration or test queries whose grid value is below A_k1 (%)", gp)
    put("AggGridLastWinnerBelowPctMax", f"{100 * max(max(x['cal_frac_H_above_cstar'], x['test_frac_H_above_cstar']) for x in G):.1f}", "largest share of queries whose last winner lies below the last checkpoint in the mu order (%)", gp)
    put("AggGridSameThresholdCount", sum(abs(x["lambda"]["grid"] - x["lambda"]["rsc"]) == 0.0 for x in G), "configurations whose grid threshold equals the RSC threshold", gp)
    put("AggGridCallsDiffMax", f"{max(abs(x['deployed']['rsc_minus_grid_calls']['mean']) for x in G):.2f}", "largest |RSC minus grid| mean deployed-order calls", gp)

    # ---- tuned micro-batch --------------------------------------------------------------------------------------
    tp = ROOT / cfg["paths"]["runs"] / "latency_tuned_diff"
    S = {(t, d): read_json(tp / t / f"{d}.json")["summary"] for t, d in keys}
    for t, tag in (("qwen3-4b", "Qwen"), ("bge-m3", "Bge")):
        s = [S[(t, d)] for d in main_domains(cfg)]
        src = tp / t

        def fmtv(fmt, v):
            if fmt == "SIGNED":
                return ("$-$" if v < 0 else "$+$") + f"{abs(v):.4f}"
            return fmt.format(v)

        def mm(name, vals, fmt, desc):
            put(f"AggTuned{tag}{name}Min", fmtv(fmt, min(vals)), f"{t}: smallest {desc}", src)
            put(f"AggTuned{tag}{name}Max", fmtv(fmt, max(vals)), f"{t}: largest {desc}", src)

        mm("MismatchPct", [100 * x["frac_mismatch"] for x in s], "{:.0f}", "share of queries whose tuned ordered top-k differs from the canonical cache (%)")
        mm("MembershipPct", [100 * x["frac_membership"] for x in s], "{:.0f}", "share of queries whose tuned top-k set differs (%)")
        mm("OrderOnlySharePct", [100 * x["share_of_mismatches_order_only"] for x in s], "{:.0f}", "share of ordered mismatches that keep the same k documents (%)")
        mm("NdcgDelta", [x["ndcg10_tuned"] - x["ndcg10_canonical"] for x in s], "SIGNED", "mean nDCG@10 of the tuned list minus the canonical list")
        if tag == "Qwen":
            mm("SwapDocs", [x["membership_swapped_docs_mean"] for x in s], "{:.2f}", "mean documents swapped across the boundary when the set changes")
            mm("MemberGap", [x["membership_boundary_gap_median"] for x in s], "{:.3f}", "median canonical boundary gap on queries whose set changes (logits)")
            mm("AllGap", [x["all_boundary_gap_median"] for x in s], "{:.2f}", "median canonical boundary gap on all timed queries (logits)")
            mm("MaxDiff", [x["max_abs_diff_median"] for x in s], "{:.2f}", "median over queries of the largest |tuned - canonical| score change (logits)")
            mm("GapBelowPerturbPct", [100 * x["membership_gap_below_max_diff"] for x in s], "{:.0f}", "share of set changes whose boundary gap is below the query's largest score change (%)")
    put("TunedNQueries", S[keys[0]]["n_queries"], "timed queries re-scored per configuration", tp)

    # ---- compact cheap-model ablation (one row per configuration) -------------------------------------------------
    primary = cfg["protocol"].get("primary_regime", "finite")
    short = {"minilm": "MiniLM", "minilm-distilled": "distilled"}
    crow = []
    for t, d in keys:
        st = read_json(ROOT / cfg["paths"]["runs"] / "stats" / t / f"{d}.json")
        ab = st["cheap_variant_ablation"]
        crow.append(f"{TINY[t]}/{DTINY[d]} & {short[ab['adopted']]} & {st['calls']['rsc_mean']:.1f} / {ab['rsc_calls']:.1f} & "
                    f"{st['calls']['adaptive_prefix']['mean']:.1f} / {ab['adaptive_prefix_calls']:.1f} & "
                    f"{st['risk'][primary]['rate']:.3f} / {ab['rsc_risk']:.3f} \\\\")
    ctab = ["% AUTO-GENERATED by scripts/24_extra_numbers.py from runs/stats/<teacher>/<domain>.json (cheap_variant_ablation).",
            "\\begin{tabular}{@{}llccc@{}}", "\\toprule",
            " & adopted & \\method{} calls & prefix calls & \\method{} risk \\\\", "\\midrule", *crow, "\\bottomrule", "\\end{tabular}"]
    (ROOT / "paper" / "tables" / "tab_cheap_compact.tex").write_text("\n".join(ctab) + "\n", encoding="utf-8")

    # ---- B_all with a scale head fitted to its own target, and the risk-calls curve (A10 ii-iii) ------------------
    op = ROOT / cfg["paths"]["runs"] / "own_target"
    if all((op / t / f"{d}.json").exists() for t, d in keys):
        O = {key: read_json(op / key[0] / f"{key[1]}.json") for key in keys}
        V = {key: O[key]["ball_variants"] for key in keys}
        C = {key: O[key]["curve"] for key in keys}
        alphas = sorted(C[keys[0]], key=float)
        own = [V[key]["own_head"]["calls"] for key in keys]
        put("OwnBallCallsMin", f"{min(own):.1f}", "smallest mean calls of B_all with its own-target scale head (alpha main)", op)
        put("OwnBallCallsMax", f"{max(own):.1f}", "largest mean calls of B_all with its own-target scale head (alpha main)", op)
        shift = [V[key]["own_head"]["calls"] - V[key]["winners_head"]["calls"] for key in keys]
        put("OwnBallShiftMin", ("$-$" if min(shift) < 0 else "$+$") + f"{abs(min(shift)):.1f}", "smallest change in B_all calls from the winners' head to its own head", op)
        put("OwnBallShiftMax", ("$-$" if max(shift) < 0 else "$+$") + f"{abs(max(shift)):.1f}", "largest change in B_all calls from the winners' head to its own head", op)
        gap = [V[key]["own_head"]["calls"] - C[key]["0.05"]["rsc"]["calls"] for key in keys]
        put("OwnBallMinusRscMin", f"{min(gap):.1f}", "smallest calls of B_all (own head) minus RSC at alpha main", op)
        put("OwnBallMinusRscMax", f"{max(gap):.1f}", "largest calls of B_all (own head) minus RSC at alpha main", op)
        put("OwnBallRiskMax", f"{max(V[key]['own_head']['risk'] for key in keys):.4f}", "largest risk of B_all with its own head", op)
        cells = [(key, a) for key in keys for a in alphas]
        put("CurveAlphaMin", alphas[0], "smallest alpha of the risk-calls curve", op)
        put("CurveAlphaMax", alphas[-1], "largest alpha of the risk-calls curve", op)
        put("CurveCellsCount", len(cells), "alpha x configuration cells of the curve", op)
        put("CurveRscBelowCoverageCount", sum(C[key][a]["rsc"]["calls"] < min(C[key][a]["btop"]["calls"], C[key][a]["ball_own"]["calls"]) for key, a in cells),
            "cells where RSC needs fewer calls than both coverage rules", op)
        tg = [C[key][a]["rsc"]["calls"] - C[key][a]["traj"]["calls"] for key, a in cells]
        put("CurveTrajBelowRscMin", f"{min(tg):.1f}", "smallest calls of RSC minus the trajectory threshold over the curve", op)
        put("CurveTrajBelowRscMax", f"{max(tg):.1f}", "largest calls of RSC minus the trajectory threshold over the curve", op)
        strict = alphas[0]
        put("CurveRscBelowPrefixStrictCount", sum(C[key][strict]["rsc"]["calls"] < C[key][strict]["adaptive_once"]["calls"] for key in keys),
            "configurations where RSC needs fewer calls than the adaptive prefix at the smallest alpha", op)
        put("CurveRscBelowPrefixOtherCount", sum(C[key][a]["rsc"]["calls"] < C[key][a]["adaptive_once"]["calls"] for key, a in cells if a != strict),
            "cells above the smallest alpha where RSC needs fewer calls than the adaptive prefix", op)
        methods = ("rsc", "traj", "btop", "ball_own", "adaptive_once", "uniform_once")
        over = [(m, key, a, C[key][a][m]["risk"]) for key, a in cells for m in methods if C[key][a][m]["risk"] > float(a)]
        put("CurveRiskCellsCount", len(cells) * len(methods), "method x alpha x configuration cells of the curve", op)
        put("CurveOverAlphaCount", len(over), "cells of the curve whose test risk exceeds their alpha", op)
        put("CurveOverAlphaMethodsCount", len({m for m, _, _, _ in over}), "methods with a cell above alpha", op)
        put("CurveRscRiskWithinCount", sum(C[key][a]["rsc"]["risk"] <= float(a) for key, a in cells), "cells where RSC's test risk is within alpha", op)
        for i, (m, key, a, r) in enumerate(sorted(over, key=lambda x: float(x[2]))):
            put(f"CurveOver{'AB'[i] if i < 2 else str(i)}Alpha", a, f"alpha of curve exceedance {i + 1} ({m}, {key[0]}/{key[1]})", op)
            put(f"CurveOver{'AB'[i] if i < 2 else str(i)}Risk", f"{r:.4f}" if r < 0.1 else f"{r:.3f}", f"test risk of curve exceedance {i + 1} ({m}, {key[0]}/{key[1]})", op)
        head = ["\\method{}", "one traj.", "$B_{\\mathrm{top}}$", "$B_{\\mathrm{all}}$, own", "adaptive", "uniform"]
        rows = []
        for a in alphas:
            cell = []
            for m in methods:
                calls = float(np.mean([C[key][a][m]["calls"] for key in keys]))
                risk = 100 * max(C[key][a][m]["risk"] for key in keys)
                rs = f"{risk:.2f}" if risk < 10 else f"{risk:.1f}"
                rs = f"\\textcolor{{figred}}{{\\textbf{{{rs}}}}}" if risk > 100 * float(a) else rs
                cell.append(f"{calls:.1f} & {rs}")
            rows.append(f"{100 * float(a):.0f}\\% & " + " & ".join(cell) + " \\\\")
        ctab = ["% AUTO-GENERATED by scripts/24_extra_numbers.py from runs/own_target/<teacher>/<domain>.json.",
                "\\begin{tabular}{@{}l" + "rr" * len(methods) + "@{}}", "\\toprule",
                " & " + " & ".join(f"\\multicolumn{{2}}{{c}}{{{h}}}" for h in head) + " \\\\",
                "".join(f"\\cmidrule(l{{2pt}}r{{2pt}}){{{2 + 2 * i}-{3 + 2 * i}}}" for i in range(len(methods))),
                "$\\alpha$ & " + " & ".join("calls & \\%" for _ in methods) + " \\\\", "\\midrule", *rows, "\\bottomrule", "\\end{tabular}"]
        (ROOT / "paper" / "tables" / "tab_curve.tex").write_text("\n".join(ctab) + "\n", encoding="utf-8")

    # ---- fresh queries, never used in any design decision (A10 i) -------------------------------------------------
    fp = ROOT / cfg["paths"]["runs"] / "fresh"
    if all((fp / t / f"{d}.json").exists() for t, d in keys):
        F = {key: read_json(fp / key[0] / f"{key[1]}.json") for key in keys}
        Fm = {key: F[key]["methods"] for key in keys}
        n = {F[key]["n_fresh"] for key in keys}
        assert len(n) == 1
        put("FreshNPerDomain", f"{n.pop():,}".replace(",", "{,}"), "fresh queries per main domain", fp)

        def span(tag, vals, fmt, desc):
            put(f"Fresh{tag}Min", fmt.format(min(vals)), f"smallest {desc} on fresh queries", fp)
            put(f"Fresh{tag}Max", fmt.format(max(vals)), f"largest {desc} on fresh queries", fp)

        span("RscRisk", [Fm[key]["rsc_finite"]["risk"] for key in keys], "{:.4f}", "RSC risk at the deployed threshold")
        span("RscWitness", [Fm[key]["rsc_finite"]["witness"] for key in keys], "{:.4f}", "RSC witness risk at the deployed threshold")
        span("RscCalls", [Fm[key]["rsc_finite"]["calls"] for key in keys], "{:.1f}", "RSC mean calls at the deployed threshold")
        put("FreshRscCpHiMax", f"{max(Fm[key]['rsc_finite']['cp_hi'] for key in keys):.4f}", "largest Clopper-Pearson upper end of RSC's fresh risk", fp)
        put("FreshRscWithinCount", sum(Fm[key]["rsc_finite"]["risk"] <= alpha for key in keys), "configurations whose fresh RSC risk is within alpha", fp)
        put("FreshRscWitnessWithinCount", sum(Fm[key]["rsc_finite"]["witness"] <= alpha for key in keys), "configurations whose fresh RSC witness risk is within alpha", fp)
        for tag, name in (("Pac", "rsc_pac"), ("Marginal", "rsc_marginal"), ("Traj", "traj"), ("Env", "env13"), ("Btop", "btop"), ("Ball", "ball"), ("Prefix", "adaptive_once"), ("Uniform", "uniform_once")):
            span(f"{tag}Risk", [Fm[key][name]["risk"] for key in keys], "{:.4f}", f"{name} risk")
            put(f"Fresh{tag}RiskAboveCount", sum(Fm[key][name]["risk"] > alpha for key in keys), f"configurations whose fresh {name} risk exceeds alpha", fp)
            if "witness" in Fm[keys[0]][name]:
                span(f"{tag}Witness", [Fm[key][name]["witness"] for key in keys], "{:.4f}", f"{name} witness risk")
                put(f"Fresh{tag}WitnessAboveCount", sum(Fm[key][name]["witness"] > alpha for key in keys), f"configurations whose fresh {name} witness risk exceeds alpha", fp)
        span("RscCallsMinusPrefix", [Fm[key]["rsc_finite"]["calls"] - Fm[key]["adaptive_once"]["calls"] for key in keys], "{:.1f}", "RSC calls minus adaptive-prefix calls")
        sh = {key: F[key]["shift"] for key in keys}
        span("HkMean", [sh[key]["H_k_mean_fresh"] for key in keys], "{:.1f}", "mean last-winner rank H_k")
        span("TestHkMean", [sh[key]["H_k_mean_test_a8"] for key in keys], "{:.1f}", "mean last-winner rank H_k on the post-freeze test set (reference)")

    # ---- open-loop serving at fixed arrival rates (A11) --------------------------------------------------------------
    olp = ROOT / cfg["paths"]["runs"] / "open_loop" / "qwen3-4b"
    doms = main_domains(cfg)
    if all((olp / f"{d}.json").exists() for d in doms) and (olp / "msmarco_pass2.json").exists():
        OL = {d: read_json(olp / f"{d}.json") for d in doms}
        OL2 = read_json(olp / "msmarco_pass2.json")
        rhos = sorted(OL[doms[0]]["rhos"])
        light, load = rhos[0], 1.2
        cell = lambda d, m, rho, src=None: (src or OL[d])["cells"][f"{m}@{rho:g}"]  # noqa: E731
        put("OpenNQueries", OL[doms[0]]["n_queries"], "queries per open-loop run", olp)
        put("OpenCMax", OL[doms[0]]["c_max"], "largest number of queries in flight in the open-loop server", olp)
        put("OpenRhoMin", f"{rhos[0]:g}", "smallest offered load (x full-teacher capacity)", olp)
        put("OpenRhoMax", f"{rhos[-1]:g}", "largest offered load (x full-teacher capacity)", olp)
        put("OpenRhoLoad", f"{load:g}", "offered load quoted in the text (x full-teacher capacity)", olp)
        put("OpenCapMin", f"{min(OL[d]['c_full'] for d in doms):.2f}", "smallest closed-loop full-teacher capacity (q/s)", olp)
        put("OpenCapMax", f"{max(OL[d]['c_full'] for d in doms):.2f}", "largest closed-loop full-teacher capacity (q/s)", olp)
        for tag, m in (("Full", "full"), ("Blk", "rsc_blockers"), ("Prefix", "prefix_adaptive"), ("Rsc", "rsc")):
            w = [cell(d, m, load)["queue_wait_mean_s"] for d in doms]
            p = [cell(d, m, load)["latency_p95_s"] for d in doms]
            put(f"Open{tag}WaitMin", f"{min(w):.1f}", f"smallest mean queueing wait of {m} at the quoted load (s)", olp)
            put(f"Open{tag}WaitMax", f"{max(w):.1f}", f"largest mean queueing wait of {m} at the quoted load (s)", olp)
            put(f"Open{tag}PNineFiveMin", f"{min(p):.1f}", f"smallest p95 latency of {m} at the quoted load (s)", olp)
            put(f"Open{tag}PNineFiveMax", f"{max(p):.1f}", f"largest p95 latency of {m} at the quoted load (s)", olp)
            r = [cell(d, m, light)["latency_p95_s"] / cell(d, "full", light)["latency_p95_s"] for d in doms]
            put(f"Open{tag}LightRatioMin", f"{min(r):.2f}", f"smallest p95 ratio of {m} to the full teacher at the lightest load", olp)
            put(f"Open{tag}LightRatioMax", f"{max(r):.2f}", f"largest p95 ratio of {m} to the full teacher at the lightest load", olp)
        put("OpenRscSlowerLightCount", sum(cell(d, "rsc", light)["latency_p95_s"] > cell(d, "full", light)["latency_p95_s"] for d in doms),
            "domains where 16/8 has a higher p95 than the full teacher at the lightest load", olp)
        methods = ("full", "rsc", "rsc_blockers", "prefix_adaptive")
        rel = [abs(cell("msmarco", m, rho, OL2)["latency_p95_s"] / cell("msmarco", m, rho)["latency_p95_s"] - 1) for m in methods for rho in rhos]
        put("OpenPassTwoMaxChangePct", f"{100 * max(rel):.0f}", "largest relative change of a p95 between the two MS MARCO passes (%)", olp)
        same = sum(sorted(methods, key=lambda m: cell("msmarco", m, rho)["latency_p95_s"]) == sorted(methods, key=lambda m: cell("msmarco", m, rho, OL2)["latency_p95_s"]) for rho in rhos)
        put("OpenPassTwoSameOrderCount", same, "loads at which both MS MARCO passes order the four methods by p95 identically", olp)
        put("OpenLoadsCount", len(rhos), "offered loads per domain", olp)
        util = {m: [c["token_utilisation"] for d in doms for c in OL[d]["cells"].values() if c["method"] == m] for m in methods}
        for tag, m in (("Full", "full"), ("Rsc", "rsc"), ("Blk", "rsc_blockers")):
            put(f"Open{tag}UtilMin", f"{min(util[m]):.2f}", f"smallest real/padded token utilisation of {m}", olp)
            put(f"Open{tag}UtilMax", f"{max(util[m]):.2f}", f"largest real/padded token utilisation of {m}", olp)
        agree = [c["agree_with_cache"] for d in doms for c in OL[d]["cells"].values() if c["method"] == "full"]
        put("OpenFullAgreeMin", f"{min(agree):.3f}", "smallest agreement of the live full teacher with the cached top-k", olp)
        rng_seed = 20261009
        code = {"nq": 1, "hotpotqa": 2, "msmarco": 3}
        realized = []
        for d, p in [(d, 1) for d in doms] + [("msmarco", 2)]:
            u = np.cumsum(np.random.default_rng(np.random.SeedSequence([rng_seed, code[d], p])).exponential(1.0, size=OL[doms[0]]["n_queries"]))
            realized.append((len(u) - 1) / (u[-1] - u[0]))
        put("OpenRealizedRateMin", f"{min(realized):.3f}", "smallest realized/nominal arrival rate over the open-loop passes", olp)
        put("OpenRealizedRateMax", f"{max(realized):.3f}", "largest realized/nominal arrival rate over the open-loop passes", olp)
        flagged = {d: min([rho for rho in rhos if cell(d, "full", rho)["overloaded"]], default=None) for d in doms}
        put("OpenFullFlagHotpot", f"{flagged['hotpotqa']:g}", "lowest load at which the registered criterion flags the full teacher on HotpotQA", olp)
        put("OpenFullFlagOthers", f"{max(flagged['nq'], flagged['msmarco']):g}", "lowest load at which the registered criterion flags the full teacher on NQ and MS MARCO", olp)

    out = ROOT / "paper" / "numbers_extra.tex"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out} and paper/tables/tab_witness.tex")
    return 0


if __name__ == "__main__":
    sys.exit(main())
