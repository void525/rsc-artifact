"""Number provenance: every number that appears in the paper must come from
here.

Workflow
--------
1. Experiment scripts call :func:`register` with a *key*, a *value*, the
   *source artifact path* and a short *description*.  Records accumulate in
   ``runs/provenance/registry.json``.
2. ``python scripts/12_paper_numbers.py`` renders ``paper/numbers.tex`` with one
   ``\\newcommand`` per key (``\\numKEY``) and ``paper/numbers.json``.
3. ``paper/tools/check_paper.py`` fails the build if the .tex sources contain
   hand-typed result numbers in result sections, if any ``\\num...`` macro is
   undefined, or if a registered source artifact's hash changed since
   registration.

Keys are ``[A-Za-z]+`` only (LaTeX macro names cannot contain digits or
underscores), e.g. ``nqRscCallsMean``.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
import time
from pathlib import Path
from typing import Any, Dict, Optional

__all__ = ["register", "load_registry", "render_numbers_tex", "verify_registry", "fmt", "macro_key"]

REGISTRY_DEFAULT = Path("runs/provenance/registry.json")
KEY_RE = re.compile(r"^[A-Za-z]+$")
_DIGITS = {"0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four", "5": "Five", "6": "Six", "7": "Seven", "8": "Eight", "9": "Nine"}


def macro_key(*parts: str) -> str:
    """Build a valid macro key from arbitrary strings: CamelCase words, digits
    spelled out, everything else dropped (e.g. 'qwen3-4b' -> 'QwenThreeFourb')."""
    out = []
    for p in parts:
        for tok in re.split(r"[^A-Za-z0-9]+", str(p)):
            if not tok:
                continue
            word = "".join(_DIGITS[c] if c.isdigit() else c for c in tok)
            out.append(word[0].upper() + word[1:])
    return "".join(out)


def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def load_registry(path: Path = REGISTRY_DEFAULT) -> Dict[str, Dict[str, Any]]:
    path = Path(path)
    if path.exists():
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)
    return {}


def _save(reg: Dict, path: Path) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(".tmp")
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(reg, f, indent=1, sort_keys=True, ensure_ascii=False)
    os.replace(tmp, path)


def fmt(value: Any, digits: int = 3) -> str:
    """Canonical text form used in the paper."""
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, int):
        return f"{value:,}".replace(",", "{,}")
    if isinstance(value, float):
        if value != value:  # NaN
            return "n/a"
        if abs(value) >= 1000:
            return f"{value:,.0f}".replace(",", "{,}")
        return f"{value:.{digits}f}"
    return str(value)


def register(key: str, value: Any, source: str, description: str, digits: int = 3, registry: Path = REGISTRY_DEFAULT, allow_overwrite: bool = True) -> Dict[str, Any]:
    if not KEY_RE.match(key):
        raise ValueError(f"key {key!r} must match [A-Za-z]+ (LaTeX macro name)")
    src = Path(source)
    rec = {
        "value": value,
        "text": fmt(value, digits),
        "source": str(source),
        "source_sha256": _sha256(src) if src.exists() else None,
        "description": description,
        "registered_at": time.strftime("%Y-%m-%dT%H:%M:%S"),
    }
    reg = load_registry(registry)
    if key in reg and not allow_overwrite and reg[key]["value"] != value:
        raise ValueError(f"key {key} already registered with a different value")
    reg[key] = rec
    _save(reg, registry)
    return rec


def render_numbers_tex(out_tex: Path = Path("paper/numbers.tex"), registry: Path = REGISTRY_DEFAULT, out_json: Optional[Path] = Path("paper/numbers.json")) -> int:
    reg = load_registry(registry)
    lines = ["% AUTO-GENERATED by scripts/12_paper_numbers.py -- DO NOT EDIT BY HAND", "% One macro per registered number; provenance in runs/provenance/registry.json", ""]
    for key in sorted(reg):
        rec = reg[key]
        lines.append(f"\\newcommand{{\\num{key}}}{{{rec['text']}}} % {rec['description']} <- {rec['source']}")
    out_tex = Path(out_tex)
    out_tex.parent.mkdir(parents=True, exist_ok=True)
    out_tex.write_text("\n".join(lines) + "\n", encoding="utf-8")
    if out_json is not None:
        Path(out_json).write_text(json.dumps({k: v["value"] for k, v in reg.items()}, indent=1, sort_keys=True), encoding="utf-8")
    return len(reg)


def verify_registry(registry: Path = REGISTRY_DEFAULT) -> Dict[str, str]:
    """Return {key: problem} for every record whose source file is missing or
    whose hash changed since registration (stale numbers)."""
    reg = load_registry(registry)
    problems = {}
    for key, rec in reg.items():
        src = Path(rec["source"])
        if not src.exists():
            problems[key] = f"source missing: {src}"
        elif rec.get("source_sha256") and _sha256(src) != rec["source_sha256"]:
            problems[key] = f"source changed since registration: {src}"
    return problems
